"""Database tables (PostgreSQL in production, SQLite for local tests).

Each business record (client, appointment, payment, ...) is one row. The columns used for
filtering and totals are real typed columns; the full record the app edits lives in `data`
(JSONB on Postgres), so new app fields don't need a migration.
"""
import os
from datetime import date

from sqlalchemy import (JSON, BigInteger, Column, Date, DateTime, ForeignKey, Index, Integer, MetaData, String, Table,
                        create_engine, func)
from sqlalchemy.dialects.postgresql import JSONB

Json = JSON().with_variant(JSONB(), "postgresql")
metadata = MetaData()

owners = Table(
    "owners", metadata,
    Column("id", Integer, primary_key=True),
    Column("email", String(254), nullable=False, unique=True),
    Column("password_hash", String(200), nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
)

# Only a SHA-256 of each session token is stored, so a database leak doesn't leak live sessions.
sessions = Table(
    "sessions", metadata,
    Column("token_hash", String(64), primary_key=True),
    Column("owner_id", ForeignKey("owners.id", ondelete="CASCADE"), nullable=False, index=True),
    Column("expires_at", DateTime(timezone=True), nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
)

# Settings, categories and payment methods, plus the version number used for optimistic locking.
profiles = Table(
    "profiles", metadata,
    Column("owner_id", ForeignKey("owners.id", ondelete="CASCADE"), primary_key=True),
    Column("version", Integer, nullable=False),
    Column("data", Json, nullable=False),
    Column("updated_at", DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()),
)


def _iso_date(v):
    try:
        return date.fromisoformat(v) if isinstance(v, str) else None
    except ValueError:
        return None


def _cents(v):
    return int(v) if isinstance(v, (int, float)) and not isinstance(v, bool) else None


def _text(n):
    return lambda v: v[:n] if isinstance(v, str) else None


# app list key -> (table name, [(column, type, app field, converter)])
KINDS = {
    "services": ("services", [("name", String(200), "name", _text(200)), ("price_cents", BigInteger, "price", _cents)]),
    "clients": ("clients", [("name", String(200), "name", _text(200))]),
    "appts": ("appointments", [("date", Date, "date", _iso_date), ("client_id", String(64), "clientId", _text(64)),
                               ("status", String(20), "status", _text(20)), ("price_cents", BigInteger, "price", _cents)]),
    "payments": ("payments", [("date", Date, "date", _iso_date), ("client_id", String(64), "clientId", _text(64)),
                              ("appt_id", String(64), "apptId", _text(64)), ("method", String(40), "method", _text(40)),
                              ("amount_cents", BigInteger, "amount", _cents)]),
    "expenses": ("expenses", [("date", Date, "date", _iso_date), ("category", String(80), "category", _text(80)),
                              ("amount_cents", BigInteger, "amount", _cents)]),
    "stock": ("stock", [("name", String(200), "name", _text(200))]),
}

record_tables = {}
for kind, (name, cols) in KINDS.items():
    t = Table(
        name, metadata,
        Column("owner_id", ForeignKey("owners.id", ondelete="CASCADE"), primary_key=True),
        Column("id", String(64), primary_key=True),  # generated by the app, so retries are idempotent
        Column("pos", Integer, nullable=False),       # keeps the app's list order (e.g. her service menu)
        *[Column(c, typ) for c, typ, _, _ in cols],
        Column("data", Json, nullable=False),
        Column("updated_at", DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()),
    )
    if any(c == "date" for c, *_ in cols):
        Index(f"ix_{name}_owner_date", t.c.owner_id, t.c.date)
    record_tables[kind] = t


def columns_for(kind, item):
    """Typed columns pulled out of one app record."""
    return {col: conv(item.get(field)) for col, _, field, conv in KINDS[kind][1]}


def database_url():
    url = os.environ.get("DATABASE_URL", "sqlite:///./dev.db")
    # Hosts hand out postgres:// URLs; SQLAlchemy needs the driver named.
    for prefix in ("postgres://", "postgresql://"):
        if url.startswith(prefix):
            return "postgresql+psycopg://" + url[len(prefix):]
    return url


def make_engine(url=None):
    url = url or database_url()
    args = {"connect_args": {"check_same_thread": False}} if url.startswith("sqlite") else {"pool_pre_ping": True}
    return create_engine(url, **args)
